/**
 * Серия без ошибок, как её видит экран.
 *
 * Два числа, а не одно: игрок держит в голове множитель, но растёт он от
 * длины серии, и без неё непонятно, сколько осталось до следующей ступени.
 */
export interface ComboState {
    /** Сколько добычи поймано подряд. Ноль — серии нет. */
    readonly streak: number;
    /** На сколько умножаются очки за добычу. Единица — множителя нет. */
    readonly multiplier: number;
}
