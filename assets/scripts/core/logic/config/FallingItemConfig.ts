import { array, number, object, oneOf, string, variant } from '../../../utils/schema/builders';
import { Infer } from '../../../utils/schema/Schema';

/**
 * Как предмет летит. Траектория привязана к типу: банан всегда виляет, арбуз
 * всегда разгоняется — игрок узнаёт поведение по картинке, а не гадает.
 *
 * Ветка выбирается меткой `kind`, и в типе получается такое же объединение:
 * фабрика поведений разбирает его `switch`, без приведений и без «а вдруг
 * поля нет».
 */
const FALL = variant('kind', {
    uniform: {},
    zigzag: {
        /** Размах виляния вбок от вертикали, точки. */
        amplitude: number({ min: 1 }),
        /** Время одного полного виляния, секунды. */
        period: number({ min: 0.1 }),
    },
    accelerated: {
        /** Прибавка к скорости за секунду, точек в секунду за секунду. */
        acceleration: number({ min: 1 }),
    },
});

export type FallConfig = Infer<typeof FALL>;

/**
 * Что предмет делает с серией. Одно поле вместо трёх правил в коде:
 *
 * `grow` — добыча: пойманная удлиняет серию, упущенная её обнуляет, и только
 * ей идут очки с множителем.
 * `drop` — кислое: пойманное укорачивает серию на единицу и платит своими
 * очками без множителя. Выбор «очки сейчас или множитель дальше».
 * `reset` — мухомор: пойманный обнуляет серию целиком, а сколько это стоит
 * жизней, говорят числа.
 *
 * Упущенные `drop` и `reset` не стоят ничего: игрок поступил правильно.
 *
 * Вывести это из чисел нельзя: у кислого фрукта и очки положительные, и жизни
 * нетронуты — от добычи его отличает только то, чем он оказывается в серии.
 */
const COMBO = oneOf('grow', 'drop', 'reset');

export type ComboEffect = Infer<typeof COMBO>;

/** Один тип падающего предмета: и фрукт, и мухомор описываются одной строкой. */
const ITEM = object({
    /** Ключ типа; он же имя в логах и в ошибках конфига. */
    id: string(),
    combo: COMBO,
    /** Имя картинки: по нему предмет находит свой спрайт. */
    texture: string(),
    /**
     * Половина ширины предмета. Одно число задаёт и размер на экране, и форму
     * для разбора ловли — двум числам разъехаться тогда негде.
     */
    radius: number({ min: 1 }),
    /** Очки за поимку. */
    score: number({ min: 0 }),
    /**
     * Что поимка делает с запасом жизней: у фруктов ноль, у мухомора минус
     * один. Только вниз: жизнь, которую фрукт дарит, — отдельная механика, а не
     * знак числа, и пока её нет.
     */
    lifeChange: number({ min: -3, max: 0 }),
    /** Вес в случайном выборе типа: чем больше, тем чаще появляется. */
    weight: number({ min: 0.001 }),
    /** Скорость снижения, точек в секунду. */
    speed: number({ min: 1 }),
    fall: FALL,
});

export type FallingItemConfig = Infer<typeof ITEM>;

/**
 * Таблица типов. Пустой быть не может — падать станет нечему; `id` в ней
 * уникальны — по нему предмет находит своё поведение.
 */
const ITEMS = array(ITEM, { min: 1, uniqueBy: 'id' });

/**
 * Насколько далеко предмет уходит вбок от точки появления.
 *
 * Нужно тому, кто выбирает эту точку: у зигзага размах прибавляется к
 * половине ширины, иначе банан уезжал бы за край поля. Знание это про правила
 * падения, а не про сцену, поэтому живёт здесь, а не в спавнере.
 */
export function horizontalReach(config: FallingItemConfig): number {
    return config.fall.kind === 'zigzag' ? config.radius + config.fall.amplitude : config.radius;
}

/**
 * Разбирает таблицу типов. Первый аргумент — то, что вернул источник конфигов,
 * то есть `unknown`: доверять ему нельзя, пока не проверено каждое поле.
 */
export function readFallingItems(raw: unknown, source = 'falling-items'): readonly FallingItemConfig[] {
    return ITEMS.parse(raw, source);
}
