/** Смещение от точки появления. По оси Y вниз — это отрицательные числа. */
export interface FallOffset {
    readonly x: number;
    readonly y: number;
}

/**
 * Траектория падения.
 *
 * Позиция предмета — чистая функция от времени его жизни, а не приращение за
 * кадр. Отсюда три следствия, ради которых так и сделано: ошибка не копится,
 * путь одинаков на 30 и на 144 кадрах в секунду, а сама траектория проверяется
 * без сцены и без движка — обычным вызовом.
 *
 * Реализации не хранят состояния и потому общие: один экземпляр на тип
 * предмета обслуживает сколько угодно летящих одновременно.
 */
export interface FallBehaviour {
    /** Куда предмет сместился к моменту `age` секунд после появления. */
    offsetAt(age: number): FallOffset;
}
