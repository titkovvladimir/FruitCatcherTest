import { FallBehaviour, FallOffset } from './FallBehaviour';

/**
 * Тот же путь, пройденный быстрее или медленнее.
 *
 * Сложность меняет темп падения одним числом и меняет его сразу для всех
 * траекторий: обёртка не знает, что внутри, — она сжимает время. Множитель
 * 1.25 значит «предмет проходит поле в 1.25 раза быстрее», и рисунок пути при
 * этом не меняется вовсе: банан виляет теми же петлями, арбуз разгоняется по
 * той же дуге.
 *
 * Считать то же самое внутри каждой траектории пришлось бы по-разному — у
 * равномерной множится скорость, у зигзага вдобавок укорачивается период, у
 * ускоренной ускорение растёт квадратом множителя, — и каждая новая траектория
 * приносила бы четвёртую формулу.
 */
export class TempoFallBehaviour implements FallBehaviour {
    constructor(
        private readonly inner: FallBehaviour,
        private readonly tempo: number,
    ) {}

    offsetAt(age: number): FallOffset {
        return this.inner.offsetAt(age * this.tempo);
    }
}
