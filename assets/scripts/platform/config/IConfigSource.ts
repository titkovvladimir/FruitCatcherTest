/**
 * Откуда берутся сырые данные конфигов.
 *
 * Правила игры знают этот контракт и не знают, что за ним стоит: в игре —
 * подключённые к сцене `JsonAsset`, в тесте — обычный объект. Отдаётся
 * намеренно `unknown`: источник отвечает за доставку, а не за содержимое.
 * Содержимое проверяет тот, кто его разбирает.
 */
export interface IConfigSource {
    /** Сырые данные документа по имени. Документа нет — исключение. */
    read(name: string): unknown;
}
