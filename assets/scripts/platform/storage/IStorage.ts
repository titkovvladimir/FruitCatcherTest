/**
 * Где игра держит то, что переживает вкладку.
 *
 * Мета знает этот контракт и не знает, что за ним стоит: в игре —
 * `localStorage` браузера, в тесте — обычная карта в памяти. Значение — строка:
 * что в ней лежит и как разбирается, решает тот, кто её пишет.
 *
 * Ошибки хранилище не бросает. Приватный режим, переполненная квота, отключённые
 * куки — обычная жизнь браузера, и падать из-за них игре нечего: не записалось
 * значит не записалось, рекорд не переживёт вкладку, а раунд играется дальше.
 */
export interface IStorage {
    /** Значение по ключу или `null`, если его нет или прочитать не вышло. */
    read(key: string): string | null;

    /** Записывает значение. Не вышло — молча, см. заметку о политике выше. */
    write(key: string, value: string): void;
}
