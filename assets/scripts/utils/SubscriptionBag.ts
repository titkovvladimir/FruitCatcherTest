import { Subscribable } from './Signal';

/**
 * Подписки скопом: сумка хранит функции отписки и гасит их одной строкой.
 *
 * Подписываться в обход сумки не нужно нигде. Дисциплина «не забудь отписаться»
 * держится на внимательности и рано или поздно протекает, а объект из пула
 * делает протечку невидимой: он не уничтожается, а выключается, и подписка,
 * сделанная один раз при рождении, переживает возврат в пул и удваивается при
 * следующей выдаче.
 *
 * Отсюда пара вызовов у пулуемого компонента: подписка в `onEnable`, `clear()`
 * в `onDisable` и он же в `onDestroy` — узел может быть уничтожен и активным,
 * например при смене сцены. Повторный `clear()` ничего не стоит.
 */
export class SubscriptionBag {
    private offs: (() => void)[] = [];

    add<T>(signal: Subscribable<T>, handler: (value: T) => void): void {
        this.offs.push(signal.on(handler));
    }

    clear(): void {
        for (const off of this.offs) {
            off();
        }
        this.offs.length = 0;
    }
}
