/**
 * Источник случайности.
 *
 * Прячет `Math.random` за контрактом ровно ради одного: правила, которые
 * бросают кости, иначе нельзя проверить. С подставленной последовательностью
 * веса спавна и разброс интервалов становятся обычной арифметикой.
 */
export interface RandomSource {
    /** Число от нуля включительно до единицы не включительно. */
    next(): number;
}
